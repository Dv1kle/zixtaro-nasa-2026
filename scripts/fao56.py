T11 = ['rice', 'cassava year 1', 'sweet potato', 'groundnut', 'green gram cowpeas', 'beans dry', 'cotton', 'millet', 'sugarcane', 'sesame',
       'safflower', 'castor beans', 'tomato', 'onion dry', 'cabbage', 'sweet peppers bell', 'water melons', 'eggplant']


def num(x):
    return float(str(x).strip())


def main() -> None:
    t = FAO56Tables()
    t12, t22, t11 = {}, {}, []
    for _, r in t.table12.iterrows():
        k = str(r['Crop']).strip()
        if k in T12:
            t12[T12[k]] = [num(r['Kcmini']), num(r['Kcmmid']), num(r['Kcmend']), num(r['hmax'])]
    for _, r in t.table22.iterrows():
        k = str(r['Crop']).strip()
        if k in T22:
            t22[T22[k]] = [num(r['Zrmax1']), num(r['Zrmax2']), num(r['pbase'])]
    for _, r in t.table11.iterrows():
        k = str(r['Crop']).strip()
        if k in T11:
            t11.append({'crop': k, 'days': [int(num(r[c])) for c in ('Lini', 'Ldev', 'Lmid', 'Llate')], 'plant': str(r['Plant Date']).strip(), 'region': str(r['Region']).strip()})
    missing = sorted(set(T12.values()) - set(t12)) + sorted(set(T22.values()) - set(t22))
    if missing:
        raise SystemExit(f'not found: {missing}')
    out = Path(__file__).resolve().parent.parent / 'src/lib/fao56-pyfao56.ts'
    out.write_text('\n'.join([
        '// Generated by scripts/fao56.py from pyfao56 (USDA-ARS; Thorp et al. 2022) - its transcription of FAO-56. Do not edit.',
        '// Table 12: Kc ini, mid, end, max height (m). Table 22: rooting depth min, max (m), depletion fraction p.',
        '// Table 11: stage lengths (days) with the planting period and region FAO-56 gives them for.',
        '',
        f'export const PY_T12: Record<string, [number, number, number, number]> = {json.dumps(t12, indent=1)}',
        '',
        f'export const PY_T22: Record<string, [number, number, number]> = {json.dumps(t22, indent=1)}',
        '',
        f'export const PY_T11: {{ crop: string; days: [number, number, number, number]; plant: string; region: string }}[] = {json.dumps(t11, indent=1)}',
        '',
    ]))
    print(f'wrote {out}: {len(t12)} Kc rows, {len(t22)} rooting rows, {len(t11)} stage rows')


if __name__ == '__main__':
    main()
